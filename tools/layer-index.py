"""Generate the layer reference strictly from its three mechanical headers."""
import argparse, pathlib, re
root = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
lines = ['# Layer reference', '', 'Generated by `python3 tools/layer-index.py`. Edit the three headers in each layer.', '', '| Layer | Owns | Reads | Emits |', '|---|---|---|---|']
for file in sorted((root / 'layers').glob('*.js')):
    text = file.read_text()
    fields = []
    for key in ['owns', 'reads', 'emits']:
        matches = re.findall(r'^// ' + key + r':\s*(.+)$', text, re.M)
        assert len(matches) == 1, f'{file.name}: expected one {key} header'
        fields.append(matches[0].replace('|', '&#124;'))
    lines.append('| [' + file.name + '](../layers/' + file.name + ') | ' + ' | '.join(fields) + ' |')
out = '\n'.join(lines) + '\n'; target = root / 'docs/LAYERS.md'
if args.check:
    assert target.read_text() == out, 'layer reference is stale'
else:
    target.write_text(out)
print(f'layer headers: {len(lines)-6} files; reference matches')
